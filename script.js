function importDataFile(event) {
  const input = event.currentTarget;
  const file = input.files?.[0];
  input.value = "";
  if (!file) return;
  if (file.size > 5 * 1024 * 1024) {
    showToast("Файл слишком большой. Максимальный размер копии — 5 МБ.");
    return;
  }
  const reader = new FileReader();
  reader.onerror = () => showToast("Не удалось прочитать файл резервной копии.");
  reader.onload = () => {
    try {
      const backup = JSON.parse(String(reader.result || ""));
      const imported = validateImportedBackup(backup);
      const sourceProfile = backup.profileName ? ` из профиля «${backup.profileName}»` : "";
      if (!window.confirm(`Восстановить копию${sourceProfile} в профиль «${activeProfile.name}»? Данные этого профиля на устройстве будут заменены.`)) return;
      const previousData = data;
      const previousPlans = workoutPlans;
      data = imported;
      workoutPlans = data.plans;
      if (!saveData()) {
        data = previousData;
        workoutPlans = previousPlans;
        return;
      }
      document.querySelector("#import-status").textContent = "Копия восстановлена.";
      renderPlan();
      renderCalendar();
      renderBodyMetrics();
      renderHistory();
      showView("overview");
      renderOverview();
      window.scrollTo(0, 0);
      showToast("Резервная копия восстановлена");
    } catch (error) {
      showToast(error instanceof SyntaxError ? "Файл не является корректным JSON." : (error.message || "Не удалось восстановить копию."));
    }
  };
  reader.readAsText(file);
}

function exportData() {
  const backup = { format: "ritm-backup", version: 1, profileId: activeProfile.id, profileName: activeProfile.name, exportedAt: new Date().toISOString(), sessions: data.sessions, currentSession: data.currentSession, daily: data.daily, scheduled: data.scheduled, plans: data.plans, exerciseLibrary: data.exerciseLibrary, programCycle: data.programCycle, weeklyGoal: weeklyGoal() };
  const contents = JSON.stringify(backup, null, 2);
  if (window.AndroidBackup) {
  window.AndroidBackup.save(contents, `ritm-${activeProfile.id}-backup-${localDateKey()}.json`);
    return;
  }
  const blob = new Blob([contents], { type: "application/json" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = `ritm-${activeProfile.id}-backup-${localDateKey()}.json`;
  link.click();
  URL.revokeObjectURL(url);
}

